def _format_list(items: list[str]) -> str:
    return "\n".join(f"- {item}" for item in items)


def _format_structures(items: list[tuple[str, str]]) -> str:
    return "\n".join(f"- {name}：{description}" for name, description in items)


def _format_scenes(items: list[dict[str, str]]) -> str:
    lines: list[str] = []
    for item in items:
        lines.extend(
            [
                f"- 场景：{item['scene']}",
                f"  输入示例：{item['input']}",
                f"  推荐结构方向：{item['structure']}",
                f"  不推荐写法：{item['avoid']}",
                f"  质量看点：{item['quality']}",
            ]
        )
    return "\n".join(lines)


def build_official_draft_rule_prompt_block(document_type: str) -> str:
    """Return the prompt block for the first-batch document-type rules."""
    normalized = (document_type or "").strip()
    rule = DOCUMENT_TYPE_RULES.get(normalized)
    if not rule:
        return "\n\n".join(
            [
                GENERAL_OFFICIAL_DRAFT_RULE,
                COMMON_STRUCTURE_GUARD,
                PARAGRAPH_REQUIREMENTS,
                MATERIAL_TRACE_REQUIREMENTS,
                ANTI_AI_REQUIREMENTS,
            ]
        )

    return "\n\n".join(
        [
            f"【首批文种规则：{normalized}】",
            "文种边界：\n" + _format_list(rule["boundary"]),
            "动态结构候选：\n" + _format_structures(rule["structures"]),
            "负面清单：\n" + _format_list(rule["negative"]),
            "标题质量要求：\n" + _format_list(rule["title_quality"]),
            "场景样例库摘要（只用于判断结构方向和质量重点，不得逐字输出）：\n" + _format_scenes(rule["scenes"]),
            COMMON_STRUCTURE_GUARD,
            PARAGRAPH_REQUIREMENTS,
            MATERIAL_TRACE_REQUIREMENTS,
            ANTI_AI_REQUIREMENTS,
        ]
    )
